@app.route(
    "/salvar",
    methods=["POST"]
)
def salvar():


    dados = request.get_json(
            silent=True
        )


    # ========================================================
    # VALIDAÇÃO INICIAL
    # ========================================================

    if not dados:

        return jsonify({

            "erro":
                "Dados não recebidos."

        }), 400


    fiscal_id = dados.get(
            "fiscal_id"
        )


    vistorias = dados.get(
            "vistorias",
            []
        )


    if not fiscal_id:

        return jsonify({

            "erro":
                "Fiscal não informado."

        }), 400


    if not vistorias:

        return jsonify({

            "erro":
                "Nenhuma vistoria recebida."

        }), 400


    conexao = conectar_banco()


    try:


        # ====================================================
        # CONFERE FISCAL
        # ====================================================

        fiscal = conexao.execute("""
                SELECT
                    id,
                    nome
                FROM fiscais
                WHERE id = %s
                  AND ativo = 1
            """,
            (
                fiscal_id,
            )
        ).fetchone()


        if fiscal is None:

            raise ValueError(
                "Fiscal inválido."
            )


        # ====================================================
        # DATA DO SERVIDOR
        # ====================================================

        agora_servidor = datetime.now()


        data_banco = agora_servidor.strftime(
                "%Y-%m-%d"
            )


        criado_em = agora_servidor.strftime(
                "%Y-%m-%d %H:%M:%S"
            )


        # ====================================================
        # CRIA UMA NOVA FISCALIZAÇÃO
        # ====================================================

        cursor = conexao.execute("""
                INSERT INTO fiscalizacoes (
                    data,
                    fiscal_id,
                    setor,
                    criado_em
                )
                VALUES (
                    %s,
                    %s,
                    'D04',
                    %s
                )
                RETURNING id
            """,
            (
                data_banco,
                fiscal_id,
                criado_em
            )
        )


        fiscalizacao_id = cursor.fetchone()["id"]


        quantidade = 0


        # ====================================================
        # PROCESSA OS LOCAIS
        # ====================================================

        for vistoria in vistorias:


            local_id = vistoria.get(
                    "local_id"
                )


            satisfatoria = vistoria.get(
                    "satisfatoria"
                )


            horario = vistoria.get(
                    "horario"
                )


            observacao = vistoria.get(
                    "observacao",
                    ""
                )


            # ------------------------------------------------
            # SIM / NÃO
            # ------------------------------------------------

            if satisfatoria not in (
                "SIM",
                "NÃO"
            ):

                raise ValueError(
                    "Resposta de vistoria inválida."
                )


            # ------------------------------------------------
            # HORÁRIO
            # ------------------------------------------------

            if not horario:

                raise ValueError(
                    "Horário da vistoria não informado."
                )


            # ------------------------------------------------
            # LOCAL
            # ------------------------------------------------

            local = conexao.execute("""
                    SELECT
                        id,
                        setor
                    FROM locais
                    WHERE id = %s
                      AND setor = 'D04'
                      AND ativo = 1
                """,
                (
                    local_id,
                )
            ).fetchone()


            if local is None:

                raise ValueError(
                    "Local de vistoria inválido."
                )


            # ------------------------------------------------
            # GRAVA VISTORIA
            # ------------------------------------------------

            conexao.execute("""
                INSERT INTO vistorias (
                    data,
                    horario,
                    fiscal_id,
                    local_id,
                    setor,
                    satisfatoria,
                    observacao,
                    criado_em,
                    fiscalizacao_id
                )
                VALUES (
                    %s,
                    %s,
                    %s,
                    %s,
                    'D04',
                    %s,
                    %s,
                    %s,
                    %s
                )
            """,
            (
                data_banco,
                horario,
                fiscal_id,
                local_id,
                satisfatoria,
                observacao,
                criado_em,
                fiscalizacao_id
            ))


            quantidade += 1


        # ====================================================
        # CONFIRMA TUDO
        # ====================================================

        conexao.commit()


        return jsonify({

            "sucesso":
                True,

            "fiscalizacao_id":
                fiscalizacao_id,

            "quantidade":
                quantidade,

            "mensagem":
                (
                    f"Fiscalização #{fiscalizacao_id} "
                    f"salva com sucesso! "
                    f"{quantidade} local(is) registrado(s)."
                )

        })


    except Exception as erro:


        conexao.rollback()


        return jsonify({

            "erro":
                str(erro)

        }), 400


    finally:

        conexao.close()


