def inicializar_banco():

    conexao = conectar_banco()

    try:
        conexao.execute("""
            CREATE TABLE IF NOT EXISTS fiscais (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome TEXT NOT NULL UNIQUE,
                ativo INTEGER NOT NULL DEFAULT 1
            )
        """)

        conexao.execute("""
            CREATE TABLE IF NOT EXISTS locais (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ordem INTEGER NOT NULL,
                setor TEXT NOT NULL,
                tipo TEXT NOT NULL,
                nome TEXT NOT NULL,
                ativo INTEGER NOT NULL DEFAULT 1,
                UNIQUE(setor, tipo, nome)
            )
        """)

        conexao.execute("""
            CREATE TABLE IF NOT EXISTS fiscalizacoes (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                data TEXT NOT NULL,
                fiscal_id INTEGER NOT NULL REFERENCES fiscais(id),
                setor TEXT NOT NULL DEFAULT 'D04',
                criado_em TEXT NOT NULL
            )
        """)

        conexao.execute("""
            CREATE TABLE IF NOT EXISTS vistorias (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                data TEXT NOT NULL,
                horario TEXT NOT NULL,
                fiscal_id INTEGER NOT NULL REFERENCES fiscais(id),
                local_id INTEGER NOT NULL REFERENCES locais(id),
                setor TEXT NOT NULL DEFAULT 'D04',
                satisfatoria TEXT NOT NULL CHECK (satisfatoria IN ('SIM', 'NÃO')),
                observacao TEXT,
                criado_em TEXT NOT NULL,
                fiscalizacao_id INTEGER REFERENCES fiscalizacoes(id)
            )
        """)

        conexao.execute(
            """
            INSERT INTO fiscais (nome, ativo)
            VALUES (%s, 1)
            ON CONFLICT (nome) DO NOTHING
            """,
            ("Ricardo Pradas",)
        )

        for ordem, tipo, nome in LOCAIS_D04:
            conexao.execute(
                """
                INSERT INTO locais (ordem, setor, tipo, nome, ativo)
                VALUES (%s, 'D04', %s, %s, 1)
                ON CONFLICT (setor, tipo, nome) DO UPDATE
                SET ordem = EXCLUDED.ordem, ativo = 1
                """,
                (ordem, tipo, nome)
            )

        conexao.commit()

    except Exception:
        conexao.rollback()
        raise

    finally:
        conexao.close()


